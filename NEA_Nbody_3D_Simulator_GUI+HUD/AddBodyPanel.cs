    internal class AddBodyPanel
    {
        Random random = new Random();

        public bool BodyReady { get; private set; }

        private string ErrorMessage;

        // string name, double mass, double radius, Color bodyColour,
        // double currentXPos, double currentYPos, double currentZPos,
        // double currentXVel, double currentYVel, double currentZVel, double speed
        public string name;
        public double mass;
        public double radius;
        public Color bodyColour;

        public double currentXPos;
        public double currentYPos;
        public double currentZPos;

        public double currentXVel;
        public double currentYVel;
        public double currentZVel;

        private UITextBox[] textBoxes = new UITextBox[10];
        public AddBodyPanel() // constructor that loops through the UI text box array object, and makes a new box before setting it in the i position in the array
        {
            for (int i = 0; i < textBoxes.Length; i++)
            {
                textBoxes[i] = new UITextBox();
                textBoxes[i].numbersOnly = !(i == 0 || i == 3); // box 0 (name) and 3 (colour) are the only ones that need letters, so this stops unwanted letters from being accepted in text boxes that arent 0 or 3
            }
        }

        // FIELDS GENERATED BY AI
        // Add Body panel state
        public bool IsOpen { get; private set; } // I changed this into a get set so that it isnt dependent on knowing whether menuIsOpen is true or not
        // Labels corresponding to the AddBody parameters
        private readonly string[] addBodyInputLabels =
        {
            "name",
            "mass",
            "radius",
            "bodyColour",
            "currentXPos",
            "currentYPos",
            "currentZPos",
            "currentXVel",
            "currentYVel",
            "currentZVel"
        };
        // END OF AI GENERATED CODE

        // METHODS GENERATED BY AI FOR THE ADD BODY PANEL
        public void OpenAddBodyPanel()
        {
            IsOpen = true;

            for (int i = 0; i < textBoxes.Length; i++) // cycle through each box and unfocus
            {
                textBoxes[i].UnFocus();
            }

            RandomBodyValues();
        }

        public void CloseAddBodyPanel()
        {
            IsOpen = false;
        }
        // END OF AI GENERATED CODE

        // AI GENERATED ADD BODY EXPANDED PANEL METHOD
        public void DrawAddBodyPanel()
        {
            const int PanelHeight = 410;
            const int PanelPadding = 15;
            const int ColumnGap = 20;
            const int RowHeight = 65;

            int panelWidth = Math.Min(680, GetScreenWidth());
            int panelY = Math.Max(0, GetScreenHeight() - PanelHeight);

            Rectangle panel = new Rectangle(0, panelY, panelWidth, PanelHeight);

            // Panel background
            DrawRectangleRec(panel, new Color(20, 20, 30, 220));
            DrawRectangleLinesEx(panel, 2, Color.DarkGray);

            // Panel heading
            DrawText("Add Body", 15, panelY + 10, 24, Color.SkyBlue);

            // Close button
            Rectangle closeButton = new Rectangle(panelWidth - 90, panelY + 8, 80, 30);

            if (DrawButton(closeButton, "Close", 25))
            {
                CloseAddBodyPanel();
                return;
            }

            float columnWidth = (panelWidth - (PanelPadding * 2) - ColumnGap) / 2f;// Calculate the width of each column

            // Draw all ten input fields
            for (int i = 0; i < textBoxes.Length; i++)
            {
                int column = i / 5;
                int row = i % 5;

                float fieldX = PanelPadding + column * (columnWidth + ColumnGap);
                float fieldY = panelY + 55 + row * RowHeight;

                // Draw parameter label
                DrawText(addBodyInputLabels[i], (int)fieldX, (int)fieldY, 20, Color.SkyBlue); // increased text box label font from 18 to increase readibility

                // Input field rectangle
                Rectangle inputBox = new Rectangle(fieldX, fieldY + 22, columnWidth, 30);

                textBoxes[i].Update(inputBox);
                textBoxes[i].Draw(inputBox);
            }

            DrawText(ErrorMessage, 15, panelY + PanelHeight - 30, 20, Color.Red); // I added this line so that it would appear inside the box and display error messages
        
        }
        // END OF AI GENERATED CODE

        public void HandleAddBodyPanelInput()
        {
            // Escape closes the panel
            if (IsKeyPressed(KeyboardKey.LeftControl)) // had to change keybind from Escape to C as escape is raylib's native exit keybind
            {
                CloseAddBodyPanel();
                return;
            }

            // Tab moves focus to the next input field
            if (IsKeyPressed(KeyboardKey.Tab)) // modified for compatibility with new class
            {
                int focusedTextBox = -1; // for unfocused

                for (int i = 0;i < textBoxes.Length; i++)
                {
                    if (textBoxes[i].IsFocused)
                    {
                        focusedTextBox = i; // records which box was focused onto 
                    }
                    textBoxes[i].UnFocus();
                }   
                
                int nextBoxToFocus = (focusedTextBox + 1) % textBoxes.Length; // moves to next box, and 0 if unfocused. Starts at -1 so -1 + 1 = 0, which is first box
                textBoxes[nextBoxToFocus].Focus(textBoxes[nextBoxToFocus].Text);
            }

            if (IsKeyPressed(KeyboardKey.Enter)) // I added this input and the calls inside it
            {
                string[] texts = textBoxes.Select(b => b.Text).ToArray(); // for each box b take its text and turn the rsult into an array

                if (ProcessInputs(texts)) // true when all sanitisation checks have passed
                {
                    BodyReadyCheck(); // sets the body label true, which GUI will read to call addbody.
                }
            }
        }

        private bool ProcessInputs(string[] inputsArray)
        {
            ErrorMessage = "";
            if (!SanitiseInput(inputsArray[0], out name)) // name
            {
                ErrorMessage = "Please input a name";
                return false;
            }
            
            if (!SanitiseInput(inputsArray[1], 0, out mass)) // Values that require positive vales
            {
                ErrorMessage = "Please input a value that isn't 0 or infinity for MASS";
                return false;
            }

            if (!SanitiseInput(inputsArray[2], 0, out radius)) // 
            {
               ErrorMessage = "Please input a positive value for RADIUS";
                return false;
            }

            if (!SanitiseInput(inputsArray[3], out bodyColour))
            {
                ErrorMessage = "Please input a valid colour";
                return false;
            }

            if (!SanitiseInput(inputsArray[4], out currentXPos)) 
            {
                ErrorMessage = $"Please input a value that isn't 0 or infinity for {addBodyInputLabels[4]}";
                return false;
            }

            if (!SanitiseInput(inputsArray[5], out currentYPos))
            {
                ErrorMessage = $"Please input a value that isn't 0 or infinity for {addBodyInputLabels[5]}";
                return false;
            }

            if (!SanitiseInput(inputsArray[6], out currentZPos))
            {
                ErrorMessage = $"Please input a value that isn't 0 or infinity for {addBodyInputLabels[6]}";
                return false;
            }

            if (!SanitiseInput(inputsArray[7], out currentXVel))
            {
                ErrorMessage = $"Please input a value that isn't 0 or infinity for {addBodyInputLabels[7]}";
                return false;
            }

            if (!SanitiseInput(inputsArray[8], out currentYVel))
            {
                ErrorMessage = $"Please input a value that isn't 0 or infinity for {addBodyInputLabels[8]}";
                return false;
            }

            if (!SanitiseInput(inputsArray[9], out currentZVel))
            {
                ErrorMessage = $"Please input a value that isn't 0 or infinity for {addBodyInputLabels[9]}";
                return false;
            }

            return true;
        }
        // string name, double mass, double radius, Color bodyColour, double currentXPos, double currentYPos, double currentZPos, double currentXVel, double currentYVel, double currentZVel, double speed

        private void BodyReadyCheck()
        {
            BodyReady = true;
        }

        public void ClearBodyReady()
        {
            BodyReady = false;
        }

        private void RandomBodyValues()
        {
            // Name with random numbers.
            int randomBodyNum = random.Next(1, 10000);            
            textBoxes[0].Text = $"Body-{randomBodyNum}";

            // random mass
            double randomMassExp = random.Next(20, 27);
            textBoxes[1].Text = $"{Math.Pow(10, randomMassExp)}";

            // radius - purely visiual 
            double randomBodyRadiusExp = random.Next(5, 8);
            double randomBodyRadius = random.Next(1, 9);
            textBoxes[2].Text = $"{randomBodyRadius * Math.Pow(10, randomBodyRadiusExp)}";

            // random colour
            List<string> colourKeys = colourCatalogue.Keys.ToList();
            string randomColour = colourKeys[random.Next(colourKeys.Count)];

            textBoxes[3].Text = $"{randomColour}";

            for (int i = 4; i <= 6; i++)
            {
                double randomPositionExp = random.Next(6, 8);
                double randomPosition = random.Next(10000, 50000);
                double randomSign = random.Next(0, 2);
                switch (randomSign)
                {
                    case 0:
                        textBoxes[i].Text = $"{randomPosition * Math.Pow(10, randomPositionExp)}";
                        break;
                    case 1:
                        textBoxes[i].Text = $"{-randomPosition * Math.Pow(10, randomPositionExp)}";
                        break;
                }   
            }

            for (int i = 7; i <= 9; i++)
            {
                double randomSpeed = random.Next(-30000, 30000);
                textBoxes[i].Text = $"{randomSpeed}";
            }  
        }
    }
